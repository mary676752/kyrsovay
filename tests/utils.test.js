import test from 'node:test';import assert from 'node:assert/strict';
import {CATEGORIES,INITIAL,normalize,validateItem,filterItems,nextId,addItem,parseStored,countByCategory} from '../src/utils.js';
const good={title:'Новая карточка',description:'Компонент для страницы',category:'layout'};
const T=(n,fn)=>test(n,fn);
T('01 количество классов',()=>assert.equal(CATEGORIES.length,4));
T('02 начальные карточки',()=>assert.equal(INITIAL.length,6));
T('03 нормализация пробелов',()=>assert.equal(normalize('  ФОРМА  '),'форма'));
T('04 нормализация null',()=>assert.equal(normalize(null),''));
T('05 валидный компонент',()=>assert.equal(validateItem(good).ok,true));
T('06 отсутствие данных',()=>assert.equal(validateItem(null).ok,false));
T('07 короткое имя',()=>assert.equal(validateItem({...good,title:'а'}).ok,false));
T('08 длинное имя',()=>assert.equal(validateItem({...good,title:'а'.repeat(61)}).ok,false));
T('09 короткое описание',()=>assert.equal(validateItem({...good,description:'abc'}).ok,false));
T('10 длинное описание',()=>assert.equal(validateItem({...good,description:'а'.repeat(241)}).ok,false));
T('11 неверный класс',()=>assert.equal(validateItem({...good,category:'unknown'}).ok,false));
T('12 обрезка имени',()=>assert.equal(validateItem({...good,title:'  Новая  '}).item.title,'Новая'));
T('13 фильтр всех',()=>assert.equal(filterItems(INITIAL).length,6));
T('14 фильтр форм',()=>assert.equal(filterItems(INITIAL,'','forms').length,2));
T('15 фильтр макета',()=>assert.equal(filterItems(INITIAL,'','layout').length,2));
T('16 фильтр меню',()=>assert.equal(filterItems(INITIAL,'','navigation').length,2));
T('17 поиск названия',()=>assert.equal(filterItems(INITIAL,'карточек').length,1));
T('18 поиск описания',()=>assert.equal(filterItems(INITIAL,'flexbox').length,1));
T('19 регистр запроса',()=>assert.equal(filterItems(INITIAL,'МЕНЮ').length,2));
T('20 неизвестная категория',()=>assert.throws(()=>filterItems(INITIAL,'','bad'),RangeError));
T('21 пустой результат',()=>assert.equal(filterItems(INITIAL,'неизвестное').length,0));
T('22 поиск и категория',()=>assert.equal(filterItems(INITIAL,'навигация','navigation').length,1));
T('23 новый id',()=>assert.equal(nextId(INITIAL),7));
T('24 id пустого набора',()=>assert.equal(nextId([]),1));
T('25 добавление',()=>assert.equal(addItem(INITIAL,good).items.length,7));
T('26 добавление не меняет исходник',()=>{addItem(INITIAL,good);assert.equal(INITIAL.length,6)});
T('27 отказ добавления',()=>assert.equal(addItem(INITIAL,{...good,title:''}).ok,false));
T('28 добавленный id',()=>assert.equal(addItem(INITIAL,good).items.at(-1).id,7));
T('29 восстановление пустого',()=>assert.equal(parseStored('').length,6));
T('30 некорректный JSON',()=>assert.equal(parseStored('{bad').length,6));
T('31 некорректная структура',()=>assert.equal(parseStored('{}').length,6));
T('32 сохранённый набор',()=>assert.equal(parseStored(JSON.stringify([{id:10,...good}])).length,1));
T('33 отбрасываем ошибки',()=>assert.equal(parseStored(JSON.stringify([{id:1,...good},{id:2,...good,title:''}])).length,1));
T('34 частоты классов',()=>assert.deepEqual(countByCategory(INITIAL),{layout:2,forms:2,navigation:2}));
T('35 пустые частоты',()=>assert.deepEqual(countByCategory([]),{layout:0,forms:0,navigation:0}));
